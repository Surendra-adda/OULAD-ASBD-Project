def find_project_root() -> Path:
    """Find the project root whether this file is dashboard/app.py or app.py."""
    here = Path(__file__).resolve().parent
    candidates = [here, *here.parents]
    for candidate in candidates:
        if (candidate / "data" / "processed" / "student_outcomes.csv").exists():
            return candidate
    # Expected placement is project_root/dashboard/app.py. Keep a reasonable fallback.
    return here.parent if here.name.lower() == "dashboard" else here


