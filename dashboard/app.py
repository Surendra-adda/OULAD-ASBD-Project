def normalize_rule_table(df: Optional[pd.DataFrame]) -> tuple[pd.DataFrame, bool]:
    """Convert a saved rule CSV to a common display table. Return table + is_reference."""
    if df is None or df.empty:
        return make_reference_rules(), True
    lower = {str(c).lower().strip(): c for c in df.columns}

    def first(*names):
        for name in names:
            if name.lower() in lower:
                return lower[name.lower()]
        return None

    antecedent_col = first("antecedents_text", "antecedent", "antecedents", "lhs", "items")
    consequent_col = first("consequent_text", "consequent", "consequents", "rhs", "outcome")
    support_col = first("support")
    confidence_col = first("confidence")
    lift_col = first("lift")
    if not all([antecedent_col, consequent_col, support_col, confidence_col, lift_col]):
        return make_reference_rules(), True

    result = pd.DataFrame()
    result["Antecedent"] = df[antecedent_col].astype(str)
    result["Outcome"] = df[consequent_col].astype(str)
    # Clean typical exported forms: outcome=Pass, frozenset({'folder', ...}), etc.
    result["Outcome"] = result["Outcome"].str.replace("outcome=", "", regex=False)
    result["Outcome"] = result["Outcome"].str.replace("final_result=", "", regex=False)
    result["Antecedent"] = result["Antecedent"].str.replace("frozenset(", "", regex=False).str.replace(")", "", regex=False)
    for col, source in [("Support", support_col), ("Confidence", confidence_col), ("Lift", lift_col)]:
        result[col] = pd.to_numeric(df[source], errors="coerce")
        # mlxtend output typically uses decimal proportions. Convert support/confidence to %.
        if col in {"Support", "Confidence"} and result[col].dropna().max() <= 1.00001:
            result[col] = result[col] * 100
    result = result.dropna(subset=["Support", "Confidence", "Lift"])
    result["Outcome"] = result["Outcome"].str.replace("frozenset(", "", regex=False).str.replace(")", "", regex=False)
    result["Outcome"] = result["Outcome"].str.replace(r"[{}'\"]", "", regex=True).str.strip()
    result["Antecedent"] = result["Antecedent"].str.replace(r"[{}'\"]", "", regex=True).str.strip()
    return result.sort_values("Lift", ascending=False), False


def student_course_keys(df: pd.DataFrame) -> list[str]:
    return [c for c in ["code_module", "code_presentation", "id_student"] if c in df.columns]


def make_dynamic_activity_patterns(activity_df: pd.DataFrame) -> pd.DataFrame:
    """Calculate outcome-specific activity prevalence lift from the currently filtered data."""
    key_cols = student_course_keys(activity_df)
    required = set(key_cols + ["final_result", "activity_type"])
    if not key_cols or not required.issubset(activity_df.columns) or activity_df.empty:
        return pd.DataFrame()
    base = activity_df[key_cols + ["final_result", "activity_type"]].dropna(subset=["final_result", "activity_type"]).copy()
    # A transaction counts once for an activity type even if the source has repeated rows.
    base = base.drop_duplicates(key_cols + ["final_result", "activity_type"])
    transactions = base[key_cols + ["final_result"]].drop_duplicates()
    n_all = len(transactions)
    if n_all == 0:
        return pd.DataFrame()
    n_by_outcome = transactions.groupby("final_result").size().to_dict()
    overall_counts = base.groupby("activity_type")[key_cols].apply(lambda x: x.drop_duplicates().shape[0])
    overall_prev = overall_counts / n_all
    group_counts = base.groupby(["final_result", "activity_type"])[key_cols].apply(lambda x: x.drop_duplicates().shape[0])
    rows = []
    for (outcome, act_type), count in group_counts.items():
        denom = n_by_outcome.get(outcome, 0)
        group_prev = count / denom if denom else float("nan")
        overall = float(overall_prev.get(act_type, 0))
        rows.append({
            "outcome": outcome,
            "activity_type": act_type,
            "students_with_activity_and_outcome": int(count),
            "outcome_group_prevalence": group_prev,
            "overall_activity_prevalence": overall,
            "lift": group_prev / overall if overall > 0 else float("nan"),
        })
    return pd.DataFrame(rows)


def chart_layout(fig, height: int = 390):
    """Apply a consistent high-contrast theme to every Plotly chart.

    Plotly has its own text styling, so page-level CSS alone is not enough.
    Explicitly style axis ticks/titles, legend text, hover labels and annotations.
    """
    fig.update_layout(
        height=height,
        margin=dict(l=48, r=24, t=58, b=52),
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="#ffffff",
        font=dict(family="DM Sans, sans-serif", color="#26334d", size=12),
        title_font=dict(size=16, color="#17233b"),
        legend=dict(
            title=dict(font=dict(color="#26334d", size=12)),
            font=dict(color="#26334d", size=12),
            bgcolor="rgba(255,255,255,0.88)",
            borderwidth=0,
        ),
        hoverlabel=dict(
            bgcolor="#17233b",
            bordercolor="#17233b",
            font=dict(family="DM Sans, sans-serif", color="#ffffff", size=12),
        ),
        coloraxis_colorbar=dict(
            tickfont=dict(color="#26334d"),
            title_font=dict(color="#26334d"),
        ),
        uniformtext=dict(minsize=10, mode="hide"),
    )
    fig.update_xaxes(
        showgrid=False, zeroline=False,
        tickfont=dict(color="#35435c", size=11),
        title_font=dict(color="#26334d", size=12),
        linecolor="#d7deea", ticks="outside",
    )
    fig.update_yaxes(
        gridcolor="#e8edf5", zeroline=False,
        tickfont=dict(color="#35435c", size=11),
        title_font=dict(color="#26334d", size=12),
        linecolor="#d7deea", ticks="outside",
    )
    # Keep pie/donut labels readable and legends dark on the light page.
    for trace in fig.data:
        if getattr(trace, "type", "") == "pie":
            trace.update(
                insidetextfont=dict(color="#ffffff", size=12),
                outsidetextfont=dict(color="#26334d", size=12),
            )
    return fig


