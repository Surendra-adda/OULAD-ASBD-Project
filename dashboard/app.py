def find_optional_file(filename: str) -> Optional[Path]:
    """Search common output locations without assuming every optional file exists."""
    candidates = [
        OUTPUT_DIR / filename,
        ROOT / filename,
        DATA_DIR / filename,
        ROOT / "results" / filename,
        ROOT / "output" / filename,
    ]
    for candidate in candidates:
        if candidate.exists() and candidate.is_file():
            return candidate
    return None


@st.cache_data(show_spinner=False)
def read_csv(path_string: str) -> pd.DataFrame:
    return pd.read_csv(path_string, low_memory=False)


def read_optional_csv(filename: str) -> Optional[pd.DataFrame]:
    path = find_optional_file(filename)
    if path is None:
        return None
    try:
        return read_csv(str(path))
    except Exception as exc:  # graceful if an optional analysis export is malformed
        st.warning(f"Could not read optional file `{path.name}`: {exc}")
        return None


